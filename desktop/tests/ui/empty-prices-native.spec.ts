import {test,expect} from '@playwright/test';
import {nativeClient,nativeAction,nativeHost} from './fixtures/native-client';

test.afterEach(async({request})=>{expect((await request.post(nativeHost+'/cleanup',{data:{}})).ok()).toBe(true);});
test('delete all products, publish an empty version, reload and publish products again',async({page,request})=>{
  await nativeClient(page,request);
  const before=await nativeAction(page,{action:'prices'});
  await page.getByRole('button',{name:'价格维护',exact:true}).click();
  const remove=page.getByRole('button',{name:/^移除商品\d+$/});
  await expect(remove).toHaveCount(before.items.length);
  while(await remove.count())await remove.first().click();
  const publish=page.getByRole('button',{name:'发布新版本',exact:true});
  await expect(publish).toBeEnabled();
  await publish.click();
  await expect(page.getByRole('dialog')).toContainText('确认发布空价格版本？已有订单和历史价格保留。');
  await page.getByRole('button',{name:'确认发布',exact:true}).click();
  await expect(page.getByRole('button',{name:'重新读取',exact:true})).toBeEnabled();
  const empty=await nativeAction(page,{action:'prices'});
  expect(empty.items).toEqual([]);
  expect(empty.price_version_id).not.toBe(before.price_version_id);
  expect(Number(empty.publication_sequence)).toBe(Number(before.publication_sequence)+1);
  await page.getByRole('button',{name:'重新读取',exact:true}).click();
  await expect(publish).toBeEnabled();
  await expect(remove).toHaveCount(0);
  await page.getByRole('button',{name:'报价工作台',exact:true}).click();
  await expect(page.getByRole('button',{name:'＋ 添加商品',exact:true})).toBeDisabled();
  await page.getByRole('button',{name:'价格维护',exact:true}).click();
  await page.getByRole('button',{name:'＋ 添加商品',exact:true}).click();
  await expect(publish).toBeDisabled();
  await page.getByLabel('商品1product_id',{exact:true}).fill('新商品');
  await page.getByLabel('商品1sale',{exact:true}).fill('25');
  await page.getByLabel('商品1cost',{exact:true}).fill('10');
  await publish.click();
  await page.getByRole('button',{name:'确认发布',exact:true}).click();
  await expect(page.getByRole('button',{name:'重新读取',exact:true})).toBeEnabled();
  const refilled=await nativeAction(page,{action:'prices'});
  expect(refilled.items[0].product_id).toBe('新商品');
  expect(Number(refilled.publication_sequence)).toBe(Number(empty.publication_sequence)+1);
});
